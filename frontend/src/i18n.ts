import type { HeadsetStatus, ReservationStatus, UserRole } from './types';

export type Language = 'en' | 'hu';

export const DAY_NAMES: Record<Language, string[]> = {
    en: ['Monday', 'Tuesday', 'Wednesday', 'Thursday', 'Friday', 'Saturday', 'Sunday'],
    hu: ['Hétfő', 'Kedd', 'Szerda', 'Csütörtök', 'Péntek', 'Szombat', 'Vasárnap'],
};

export function translateHeadsetStatus(status: HeadsetStatus, lang: Language): string {
    if (lang === 'en') return status;
    switch (status) {
        case 'Available':
            return 'Elérhető';
        case 'Maintenance':
            return 'Karbantartás';
        case 'Coming Soon...':
            return 'Hamarosan...';
        default:
            return status;
    }
}

export function translateReservationStatus(status: ReservationStatus, lang: Language): string {
    if (lang === 'en') return status;
    switch (status) {
        case 'Pending':
            return 'Függőben';
        case 'Confirmed':
            return 'Megerősítve';
        case 'Completed':
            return 'Teljesítve';
        case 'Cancelled':
            return 'Lemondva';
        default:
            return status;
    }
}

export function translateRole(role: UserRole, lang: Language): string {
    if (lang === 'en') return role;
    return role === 'Admin' ? 'Adminisztrátor' : 'Felhasználó';
}

